// Developer-only snapshot sync. Product never runs gh or this script.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),{execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const api=p=>JSON.parse(execFileSync('gh',['api',p],{encoding:'utf8',maxBuffer:32*1024*1024}));
const repo='BigPizzaV3/CodexPlusPlus-Themes';
const tree=api(`repos/${repo}/git/trees/main?recursive=1`);
const blob=(repo,sha)=>Buffer.from(api(`repos/${repo}/git/blobs/${sha}`).content,'base64');
const get=(p)=>{const file=tree.tree.find(v=>v.path===p&&v.type==='blob');if(!file)throw Error(`Missing ${p}`);return blob(repo,file.sha);};
const index=JSON.parse(get('index.json'));
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const entries=[];
for(const s of index.themes){
 if(!/^[a-z0-9-]+$/.test(s.id)||!s.theme.startsWith(`themes/${s.id}/`)||!s.image.startsWith(`themes/${s.id}/`))throw Error('Unsafe index');
 const dir=path.join(root,'assets/themes',s.id);fs.mkdirSync(dir,{recursive:true});
 for(const [p,sha] of [[s.theme,s.theme_sha256],[s.image,s.image_sha256]]){
  const dest=path.join(dir,path.basename(p));let data=fs.existsSync(dest)?fs.readFileSync(dest):null;
  if(!data||hash(data)!==sha){data=get(p);if(hash(data)!==sha)throw Error(`Hash mismatch ${p}`);fs.writeFileSync(dest,data);}
 }
 const license=get(`themes/${s.id}/LICENSE.md`);fs.writeFileSync(path.join(dir,'LICENSE.md'),license);
 entries.push({...s,image_file:path.basename(s.image),license_sha256:hash(license),catalog:'market'});
 console.log(`Verified ${s.id}`);
}
const upstream='BigPizzaV3/CodexPlusPlus';
const upstreamTree=api(`repos/${upstream}/git/trees/main?recursive=1`);
const upstreamGet=p=>blob(upstream,upstreamTree.tree.find(v=>v.path===p).sha);
const dir=path.join(root,'assets/themes/preset-arina-hashimoto');fs.mkdirSync(dir,{recursive:true});
const original=upstreamGet('assets/inject/upstream/dream-skin/windows/theme.json');
fs.writeFileSync(path.join(dir,'upstream-theme.json'),original);
const theme=JSON.parse(original);theme.schemaVersion=1;theme.id='preset-arina-hashimoto';theme.name='桥本有菜';
// Explicit fallback palette from upstream DreamSkinColors::default; no upstream CSS executed.
theme.colors={background:'#F7F4F5',panel:'#FFFFFF',panelAlt:'#FFF7F8',accent:'#E25563',text:'#2B2224',muted:'#8A7A7D',line:'rgba(196, 120, 128, .22)'};
const config=Buffer.from(JSON.stringify(theme,null,2)+'\n');fs.writeFileSync(path.join(dir,'theme.json'),config);
const image=upstreamGet('assets/inject/upstream/dream-skin/windows/dream-reference.jpg');fs.writeFileSync(path.join(dir,'image.jpg'),image);
const license=upstreamGet('assets/inject/upstream/dream-skin/LICENSE');fs.writeFileSync(path.join(dir,'LICENSE.md'),license);
entries.unshift({id:theme.id,name:theme.name,author:'Fei-Away',license:'MIT (upstream notice); image rights see original source',description:'Codex++ Windows 内置主题，使用上游默认配色转换。',source_url:'https://github.com/BigPizzaV3/CodexPlusPlus/tree/main/assets/inject/upstream/dream-skin',image_file:'image.jpg',image_sha256:hash(image),theme_sha256:hash(config),license_sha256:hash(license),catalog:'builtin'});
fs.writeFileSync(path.join(root,'desktop/ui/themes/sources.json'),JSON.stringify(entries,null,2)+'\n');
fs.writeFileSync(path.join(root,'crates/core/src/theme_assets.rs'),'// Generated by fixtures/sync-theme-market.cjs; verified snapshot.\n'+
 'pub const ASSETS: &[(&str, &[u8])] = &[\n'+entries.map(s=>`    (include_str!("../../../assets/themes/${s.id}/theme.json"), include_bytes!("../../../assets/themes/${s.id}/${s.image_file}")),`).join('\n')+'\n];\n');
fs.writeFileSync(path.join(root,'assets/themes/snapshot.json'),JSON.stringify({checked_at:'2026-10-14',market_commit:tree.sha,codex_commit:upstreamTree.sha,market_updated_at:index.updated_at,market_count:index.themes.length,builtin_count:1},null,2)+'\n');
console.log(`Complete: ${entries.length} Codex++ themes`);
